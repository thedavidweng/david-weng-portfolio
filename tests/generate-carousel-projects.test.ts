import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "vitest";
import { projects } from "@/content/projects";

const CAROUSEL_FIELDS = [
  "slug",
  "title",
  "code",
  "posterWord",
  "category",
  "year",
  "coverLabel",
  "coverPalette",
  "coverImage",
  "teaser"
] as const;

test("generate carousel-projects.ts from canonical projects data", () => {
  const carouselProjects = projects.map((project) =>
    Object.fromEntries(CAROUSEL_FIELDS.map((field) => [field, project[field]]))
  );

  const outputPath = join(process.cwd(), "content/carousel-projects.ts");
  const output = `// Generated by tests/generate-carousel-projects.test.ts — do not edit.
import type { CarouselProjectItem } from "@/types/content";

export const carouselProjects: CarouselProjectItem[] = ${JSON.stringify(carouselProjects, null, 2)} as CarouselProjectItem[];
`;

  writeFileSync(outputPath, output);
});
