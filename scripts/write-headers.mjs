import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { aliasSitemapXml } from "./sitemap-alias.mjs";

const distDir = join(process.cwd(), "dist");
const headersPath = join(distDir, "_headers");

const SECURITY_HEADERS = `/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  X-DNS-Prefetch-Control: on
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Strict-Transport-Security: max-age=63072000; includeSubDomains; preload

/
  Link: </llms.txt>; rel="llms.txt", </llms-full.txt>; rel="llms-full.txt", </index.md>; rel="index.md", </agent>; rel="agent-catalog", </sitemap.xml>; rel="sitemap", </robots.txt>; rel="robots"
`;

const ASSET_CACHE_RULES = `
# Long-lived cache for hashed build assets and portfolio media (generated by write-headers)
/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/assets/*
  Cache-Control: public, max-age=31536000, immutable

/brand/*
  Cache-Control: public, max-age=31536000, immutable

/projects/client-work/*
  Cache-Control: public, max-age=31536000, immutable

/projects/film-video/*
  Cache-Control: public, max-age=31536000, immutable

/projects/personal/*
  Cache-Control: public, max-age=31536000, immutable

/projects/personal-video/*
  Cache-Control: public, max-age=31536000, immutable

/projects/research-publication/*
  Cache-Control: public, max-age=31536000, immutable

# Short edge TTL for HTML; revalidate after deploy without immutable staleness
/
  Cache-Control: public, max-age=300, stale-while-revalidate=86400

/zh/
  Cache-Control: public, max-age=300, stale-while-revalidate=86400
`;

if (!existsSync(distDir)) {
  throw new Error(`[write-headers] Missing build output at ${distDir}. Run pnpm build first.`);
}

// @astrojs/sitemap emits sitemap-index.xml + sitemap-0.xml; preserve legacy /sitemap.xml URL.
aliasSitemapXml(distDir);

let headers = existsSync(headersPath) ? readFileSync(headersPath, "utf8") : "";

if (!headers.includes("X-Content-Type-Options")) {
  headers += SECURITY_HEADERS;
}

if (!headers.includes("/projects/*")) {
  headers += ASSET_CACHE_RULES;
}

writeFileSync(headersPath, headers);